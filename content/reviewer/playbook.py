"""Senior Engineer Playbook: behavioural interviews and leadership (original bite-sized lessons)."""
from dsl import subject, unit, bite

subject(
    id="playbook", title="Senior Engineer Playbook", icon="person.3.sequence.fill", color="#F59E0B",
    blurb="What separates senior and staff engineers: scope, judgement, communication and leadership, plus how to show it in interviews.",
    units=[
        unit("Behavioural Interviews",
             bite("pb-star", "The STAR Method",
                  "Answer behavioural questions as a story: Situation, Task, Action, Result, with numbers.",
                  ["Situation and Task: 2–3 sentences of context, no more.",
                   "Action: what you did, using 'I' not 'we'. This is the heart of the answer.",
                   "Result: measurable impact (latency −40%, incidents −60%), plus what you learned.",
                   "Keep each story under two minutes, and prepare 6–8 stories that cover many questions."],
                  example="'Our checkout p99 hit 4 s (S). I owned fixing it before Black Friday (T). I profiled, added a read-through cache and batched DB calls (A). p99 dropped to 600 ms and conversion rose 3% (R).'",
                  tip="End every story with impact and a lesson learned.",
                  quiz=("Which STAR part deserves the most time?", ["Situation", "Task", "Action", "Result"], 2,
                        "Interviewers assess what you personally did.")),
             bite("pb-story-bank", "Build a Story Bank",
                  "Prepare stories for the themes every company asks about.",
                  ["Conflict or disagreement with a colleague.",
                   "A failure or mistake and what you changed afterwards.",
                   "Leading without authority, and mentoring.",
                   "Ambiguity, tight deadlines, a hard technical decision, and handling an incident."],
                  example="One migration story can cover technical depth, influence and handling setbacks if framed differently.",
                  tip="Write the stories down and rehearse them out loud; Listen mode makes that easy on a commute.",
                  quiz=("How many prepared stories is a good target?", ["1", "6–8", "50", "None; improvise"], 1,
                        "Enough to cover the common themes without memorising scripts.")),
             bite("pb-failure", "Talking About Failure",
                  "Good failure stories show ownership, learning and changed behaviour, not blame.",
                  ["Pick a real mistake with real stakes.",
                   "Own your part clearly; avoid blaming others.",
                   "Explain the fix and the systemic change (tests, alerts, process).",
                   "Show how you've applied the lesson since."],
                  example="'I shipped a migration without a rollback plan; it failed at 2 a.m. Since then, every migration I lead has a tested rollback and a feature flag.'",
                  tip="Blameless postmortems are the senior answer to failure.",
                  quiz=("A strong failure answer emphasises…", ["who else was at fault", "what you learned and changed", "that it wasn't really a failure", "technical jargon"], 1,
                        "Interviewers look for growth and ownership.")),
             blurb="Turning your experience into convincing answers."),
        unit("Technical Leadership",
             bite("pb-design-docs", "Writing Design Docs",
                  "A design doc aligns people before code is written: the problem, options, the decision and the risks.",
                  ["Context and goals (and non-goals).",
                   "Two or three options with honest trade-offs.",
                   "The proposed design: APIs, data, rollout, migration and rollback.",
                   "Risks, open questions, metrics for success."],
                  example="A one-page doc comparing Kafka versus SQS for order events saved weeks of debate.",
                  tip="Write for the reader who wasn't in the meeting.",
                  quiz=("Why include non-goals?", ["To make the doc longer", "To prevent scope creep and set expectations", "Required by law", "To skip testing"], 1,
                        "Clear boundaries focus the work.")),
             bite("pb-code-review", "Effective Code Reviews",
                  "Reviews protect quality and spread knowledge; be fast, kind and specific.",
                  ["Look first for correctness, security, clarity and tests; leave style to linters.",
                   "Label nits as optional; separate blocking from non-blocking comments.",
                   "Ask questions instead of issuing orders; explain the why.",
                   "Keep pull requests small; review within a day."],
                  example="'Could this race if two requests arrive together? A unique constraint would make it safe.' is better than 'Wrong.'",
                  tip="Praise good code in reviews too; it reinforces good patterns.",
                  quiz=("What should automated tools handle instead of reviewers?", ["Security", "Formatting and style", "Design", "Correctness"], 1,
                        "Linters and formatters free humans for real issues.")),
             bite("pb-tech-debt", "Managing Technical Debt",
                  "Tech debt is a loan: sometimes worth taking, always worth tracking and paying down deliberately.",
                  ["Make the cost visible: incidents, slow delivery, onboarding time.",
                   "Tie paydown work to business outcomes.",
                   "Use the boy-scout rule: leave code a little better than you found it.",
                   "Reserve capacity (for example 15–20%) for maintenance."],
                  example="'This module causes 30% of our incidents; two weeks of refactoring should save a day a week of on-call time.'",
                  tip="Speak in risk, time and money, not in code-quality adjectives.",
                  quiz=("The most persuasive case for paying down debt is…", ["'the code is ugly'", "measured impact on delivery or incidents", "personal preference", "new framework hype"], 1,
                        "Business impact gets prioritised.")),
             bite("pb-incidents", "Leading Incidents and Postmortems",
                  "During incidents: stabilise first, communicate often, investigate later.",
                  ["Roles: an incident commander coordinates, others investigate and communicate.",
                   "Mitigate before root-causing: roll back, fail over, shed load.",
                   "Post regular status updates, even 'no news yet'.",
                   "Blameless postmortems: timeline, root causes, action items with owners and dates."],
                  example="Rolling back the last deploy in 5 minutes beats debugging production for an hour.",
                  tip="Ask 'what made this possible?' instead of 'who did this?'",
                  quiz=("The first priority during a production incident is…", ["finding who caused it", "mitigating user impact", "writing the postmortem", "refactoring"], 1,
                        "Stop the bleeding, then investigate.")),
             bite("pb-estimation", "Estimation and Delivery",
                  "Estimate with ranges, break work into milestones, and surface risk early.",
                  ["Split work until each piece takes a few days at most.",
                   "Give ranges with confidence ('2–3 weeks, 80% confident'), not single dates.",
                   "Tackle the riskiest unknowns first (spikes, prototypes).",
                   "Communicate slips early along with options: cut scope, add time or add help."],
                  example="'The search migration is 3–5 weeks; the risk is re-indexing time, which I'll measure this week.'",
                  tip="Bad news early is a gift; bad news late is a crisis.",
                  quiz=("What's the most senior way to handle a likely slip?", ["Stay quiet and work weekends", "Raise it early with options", "Blame requirements", "Lower quality"], 1,
                        "Early transparency lets the team adjust.")),
             blurb="Multiplying the impact of everyone around you."),
        unit("Influence & Growth",
             bite("pb-mentoring", "Mentoring and Growing Others",
                  "Senior engineers are measured by team output, not personal output.",
                  ["Pair on hard problems instead of taking them over.",
                   "Delegate stretch tasks with support and clear success criteria.",
                   "Give specific, timely feedback: situation, behaviour, impact.",
                   "Document decisions so knowledge doesn't live only in your head."],
                  example="Helping a junior engineer own the on-call runbook grows them and removes you as a bottleneck.",
                  tip="If you're the only one who can fix something, that's a risk to fix.",
                  quiz=("A sign of senior impact is…", ["writing all the hard code yourself", "others becoming more effective because of you", "working the longest hours", "knowing every tool"], 1,
                        "Leverage through others is the senior multiplier.")),
             bite("pb-influence", "Influence Without Authority",
                  "Persuade with data, empathy and small experiments rather than titles.",
                  ["Understand stakeholders' goals and constraints first.",
                   "Bring evidence: metrics, prototypes, customer quotes.",
                   "Propose a reversible experiment to lower the stakes.",
                   "Disagree and commit once a decision is made."],
                  example="A one-week spike showing 40% lower latency convinced the team to adopt a new caching layer.",
                  tip="People support what they help create: involve them early.",
                  quiz=("After losing a technical debate, a senior engineer should…", ["keep reopening it", "disagree and commit", "build their version secretly", "escalate immediately"], 1,
                        "Alignment beats being right in the abstract.")),
             bite("pb-transition-ai", "Moving From SWE to AI Engineering",
                  "Lean on what you already have (APIs, testing, systems) and add evaluation, retrieval and model literacy.",
                  ["Learn the core concepts: embeddings, transformers, tokens, RAG, agents, evals.",
                   "Ship a small end-to-end project: a RAG assistant with evals, tracing and cost tracking.",
                   "Write about it: a design doc and the evaluation results.",
                   "Interviews mix coding, ML and LLM fundamentals, and AI system design."],
                  example="Turn an internal FAQ into a RAG bot, measure answer accuracy on 100 questions, then improve retrieval and show the gains.",
                  tip="Follow the AI Engineer career path in Learn: it sequences exactly these steps.",
                  quiz=("The strongest portfolio piece for an AI engineering role is…", ["a list of courses", "a shipped LLM app with an eval suite and metrics", "a Kaggle badge only", "a model trained from scratch"], 1,
                        "It demonstrates production judgement end to end.")),
             blurb="Growing your scope and your career."),
    ],
)
